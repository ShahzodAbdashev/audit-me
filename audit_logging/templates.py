#: The token standing in for the dataset in :data:`INDEX_TEMPLATE` and in
#: ``infra/elasticsearch/template-apiaudit.json``. Both carry the *unbound*
#: template; :func:`index_template_for` binds it to one dataset.
#:
#: The template is per dataset, not per package. It has ``priority: 500``,
#: which outranks Elasticsearch's built-in ``logs`` template (100), so a
#: pattern any wider than the dataset's own indices would impose this
#: package's ``dynamic: false`` mapping on unrelated ``logs-*-*`` data
#: streams and strip every field from their documents.
DATASET_PLACEHOLDER = "{dataset}"


def index_template_name_for(dataset: str) -> str:
    """``logs-<dataset>`` — the name this template is installed under."""
    return f"logs-{dataset}"


def ilm_policy_name_for(dataset: str) -> str:
    """``<dataset>-ilm`` — the policy name this template's indices reference."""
    return f"{dataset}-ilm"


def index_template_for(dataset: str) -> dict[str, Any]:
    """:data:`INDEX_TEMPLATE` bound to one dataset, as a fresh dict.

    Substitutes :data:`DATASET_PLACEHOLDER` in ``index_patterns``, in the
    lifecycle policy name and in ``_meta``. A deep copy, so a caller that
    edits the result — the shipper rewrites the ILM phases — cannot corrupt
    the module-level constant for the next caller.
    """
    bound = json.loads(json.dumps(INDEX_TEMPLATE).replace(DATASET_PLACEHOLDER, dataset))
    return dict(bound)

#: The one retention knob. ``None`` means **never delete**, which is the
#: shipped default and why :data:`ILM_POLICY` carries no ``delete`` phase.
#: ``AuditConfig.retention_days`` overrides it; the shipper adds a delete
#: phase back when it is a number.
DEFAULT_RETENTION_DAYS: int | None = None

