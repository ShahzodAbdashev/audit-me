"""The Elasticsearch index template and ILM policy, as data.

Generated from ``infra/elasticsearch/*.json`` — that copy is for operators
applying them with ``curl`` or ``bootstrap.py``; this one is for
``ElasticsearchShipper``, so a ``pip install`` is self-contained and nobody has
to fetch a file out of the repository to get a correct mapping.

The two are checked against each other by ``tests/unit/test_templates.py``. If
they drift, that test fails — rather than a cluster silently getting the wrong
mapping.

``dynamic: false`` is the load-bearing property. Without it Elasticsearch
invents a field for every distinct body shape and the mapping grows until it
refuses writes: measured, 10 000 documents produce 51 fields with it and 20 194
without. Do not edit this file to "allow" a new field.
"""

